// Extrae todos los grupos de digitos de un nombre y los devuelve como numeros.
// "cloud_1583836591_182590976.pcd" -> {1583836591, 182590976}
std::vector<std::uint64_t> ExtractNumbers(const std::string& name) {
    std::vector<std::uint64_t> nums;
    std::size_t i = 0;
    while (i < name.size()) {
        if (std::isdigit(static_cast<unsigned char>(name[i]))) {
            std::uint64_t value = 0;
            while (i < name.size() && std::isdigit(static_cast<unsigned char>(name[i]))) {
                // Saturacion defensiva por si aparece un numero absurdamente largo.
                if (value < 1000000000000000000ULL) {
                    value = value * 10 + static_cast<std::uint64_t>(name[i] - '0');
                }
                ++i;
            }
            nums.push_back(value);
        } else {
            ++i;
        }
    }
    return nums;
}

